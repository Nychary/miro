import type { LessonMeta, Subject } from './schema'

/**
 * Сборка промпта для нейросети.
 *
 * Промпт уходит не по сети, а в буфер обмена: репетитор вставляет его в тот
 * чат, которым уже пользуется, и приносит ответ обратно. Поэтому длина промпта
 * ничего не стоит — можно позволить себе подробную схему и развёрнутые
 * требования к содержанию, что заметно поднимает качество ответа.
 *
 * Когда появится ключ, этот же текст пойдёт в системное сообщение запроса.
 * Менять придётся только транспорт.
 */

export interface LessonRequest extends Omit<LessonMeta, 'language'> {
  language: 'ru' | 'en'
  /** Что известно про ученика: уровень, пробелы, цели. Пока вводится вручную. */
  studentNotes?: string
  /**
   * Шаблон структуры урока. «five» — авторский план репетитора из пяти
   * упражнений: Вспоминаем, Новый материал, Практика, Игра, Рефлексия.
   */
  template?: 'classic' | 'five' | 'language'
  /** Тема прошлого занятия — для упражнения «Вспоминаем» в шаблоне «five». */
  prevTopic?: string
  /**
   * Какие приёмы оформления разрешены в этом уроке.
   *
   * Приём хорош, пока он событие. Коробка в каждом уроке перестаёт быть
   * коробкой и становится ещё одной формой ввода, поэтому выбор остаётся за
   * репетитором: пусто — обычные задания без приёмов.
   */
  tricks?: TrickKind[]
}

export type TrickKind = 'mysterybox' | 'halves' | 'pullout' | 'flashlight'

export const TRICK_LABELS: Record<TrickKind, string> = {
  mysterybox: 'коробка с карточками',
  halves: 'половинки',
  pullout: 'тянучка с вопросами',
  flashlight: 'фонарик',
}

export function buildPrompt(request: LessonRequest): string {
  const sections = [
    role(request.subject),
    task(request),
    styleSection(request.style),
    request.template === 'five'
      ? fiveStructure(request)
      : request.template === 'language'
        ? languageStructure(request)
        : structure(request),
    tricksSection(request.tricks),
    teacherScript(request),
    SCHEMA_SPEC,
    contentRules(request.subject),
    OUTPUT_RULES,
  ].filter((section): section is string => Boolean(section))
  return sections.join('\n\n').trim()
}

