import type { LessonMeta, Subject } from './schema'

/**
 * Сборка промпта для нейросети.
 *
 * Промпт уходит не по сети, а в буфер обмена: репетитор вставляет его в тот
 * чат, которым уже пользуется, и приносит ответ обратно. Поэтому длина промпта
 * ничего не стоит — можно позволить себе подробную схему и развёрнутые
 * требования к содержанию, что заметно поднимает качество ответа.
 *
 * Когда появится ключ, этот же текст пойдёт в системное сообщение запроса.
 * Менять придётся только транспорт.
 */

export interface LessonRequest extends Omit<LessonMeta, 'language'> {
  language: 'ru' | 'en'
  /** Что известно про ученика: уровень, пробелы, цели. Пока вводится вручную. */
  studentNotes?: string
  /**
   * Шаблон структуры урока. «five» — авторский план репетитора из пяти
   * упражнений: Вспоминаем, Новый материал, Практика, Игра, Рефлексия.
   */
  template?: 'classic' | 'five'
  /** Тема прошлого занятия — для упражнения «Вспоминаем» в шаблоне «five». */
  prevTopic?: string
}

export function buildPrompt(request: LessonRequest): string {
  const sections = [
    role(request.subject),
    task(request),
    styleSection(request.style),
    request.template === 'five' ? fiveStructure(request) : structure(request),
    teacherScript(request),
    SCHEMA_SPEC,
    contentRules(request.subject),
    OUTPUT_RULES,
  ].filter((section): section is string => Boolean(section))
  return sections.join('\n\n').trim()
}

// ---------------------------------------------------------------------------

function role(subject: Subject): string {
  return subject === 'physics'
    ? 'Ты — опытный репетитор по физике. Ты составляешь уроки для индивидуальных занятий на онлайн-доске: ученик видит доску и работает на ней вместе с преподавателем.'
    : 'Ты — опытный репетитор по английскому языку. Ты составляешь уроки для индивидуальных занятий на онлайн-доске: ученик видит доску и работает на ней вместе с преподавателем.'
}

function task(request: LessonRequest): string {
  const lines = [
    'Составь урок.',
    `Тема: ${request.topic}`,
    `Уровень: ${request.level}`,
    `Длительность: ${request.durationMin} минут`,
  ]
  if (request.student) lines.push(`Ученик: ${request.student}`)
  if (request.studentNotes?.trim()) lines.push(`Что известно про ученика: ${request.studentNotes.trim()}`)
  return lines.join('\n')
}

/**
 * Стилизация — двухслойная: формулировки делает нейросеть по этой секции,
 * а цвета подбирает рендерер по названию стиля из meta.style. Поэтому
 * критично, чтобы название вернулось в JSON без изменений.
 *
 * Особый режим — «придумай сам»: нейросеть изобретает тематическую обёртку
 * под содержание урока. Это снимает с репетитора самую затратную часть
 * оформления — придумывание темы.
 */
function styleSection(style?: string): string | null {
  const trimmed = style?.trim()
  if (!trimmed) return null

  // «Стандарт» — это просьба ничего не стилизовать, а не стиль по имени.
  if (/стандарт|обычн/i.test(trimmed)) return null

  const invent = /придумай|предложи|surprise/i.test(trimmed)

  const heading = invent
    ? [
        'Придумай тематическую обёртку урока сам: выбери тему, которая обыгрывает',
        'содержание урока и будет интересна ученику. Примеры хода мысли:',
        'Present Simple → распорядок дня Ван Гога (искусство); силы в физике →',
        'цирковые номера; проценты → открытие своей кофейни.',
        'Назови выбранную тему в meta.style (коротко, 2–4 слова).',
      ].join('\n')
    : `Стиль оформления: «${trimmed}». Верни его название без изменений в meta.style.`

  return [
    heading,
    '— Выдержи в этой эстетике заголовки блоков (поле "title"), инструкции к заданиям,',
    '  формулировки вопросов и подбадривания. Примеры подачи: «Гарри Поттер» →',
    '  «Сегодня изучаем заклинание Past Simple»; «Детектив» → «Дело №3: тайна',
    '  пропавшего сопротивления»; «Космос» → «Миссия: рассчитать ток».',
    '— Предметное содержание стилизация не искажает: условия задач, формулы,',
    '  правила и ответы остаются точными.',
    '— В meta.imageIdeas верни 3–6 готовых поисковых запросов для картинок',
    '  к оформлению: конкретных, по которым сразу найдётся нужное, например',
    '  ["Ван Гог Звёздная ночь", "Ван Гог автопортрет", "подсолнухи картина"].',
    '  Предпочитай изображения из общественного достояния (картины, гравюры,',
    '  фотографии природы), а не чужие иллюстрации и кадры.',
  ].join('\n')
}

/**
 * Авторский план репетитора: каждый урок — пять упражнений в фиксированном
 * порядке. Он заведён отдельным шаблоном, а не заменил классический, чтобы
 * было с чем сравнивать и куда откатиться.
 */
function fiveStructure(request: LessonRequest): string {
  const physics = request.subject === 'physics'
  const recall = request.prevTopic?.trim()
    ? `по прошлой теме («${request.prevTopic.trim()}»)`
    : 'по знаниям, на которые опирается новая тема'
  // Количество — с реальных занятий: на 60 минут нужно 10 задач.
  const taskCount = request.durationMin <= 45 ? '6' : request.durationMin >= 90 ? '12–14' : '10'

  return [
    'Структура урока — 5 упражнений строго в этом порядке, плюс ответы:',
    `1. warmup c "title": "Вспоминаем" — 3 вопроса ${recall}`,
    '2. mindmap — новый материал интеллект-картой: центральное понятие и 3–5 веток по 2–4 коротких тезиса' +
      (physics ? '; формулы включай в тезисы веток юникодом' : ''),
    `3. ${physics ? `tasks c "title": "Практика" — ${taskCount} задач по возрастанию сложности, с подсказками к трудным` : 'gapfill c "title": "Практика" — 4–5 предложений с пропусками плюс 2–3 лишних варианта'}`,
    '4. одна «Игра» c "title": "Игра" — выбери приём под тему: mysterybox, halves, sorting или matching',
    '5. pullout ИЛИ flashlight — второй приём, для разговора или для лексики' +
      (physics ? ' (у физики: pullout с вопросами «почему», flashlight с терминами темы)' : ''),
    '6. reflection — рефлексия; можно задать свои подписи колонок в "prompts" в стиле урока',
    '7. answers — ответы ко всем заданиям практики и игры' + (physics ? ', с ходом решения' : ''),
  ].join('\n')
}

/**
 * Состав блоков зависит от предмета и длительности. Без этого нейросеть
 * выдаёт то три задачи, то пятнадцать, и уроки перестают быть похожими друг
 * на друга — а репетитору нужна предсказуемая структура.
 */
function structure(request: LessonRequest): string {
  const scale = request.durationMin <= 45 ? 'short' : request.durationMin >= 90 ? 'long' : 'normal'

  if (request.subject === 'physics') {
    // Количество — с реальных занятий: на 60 минут нужно 10 задач.
    const tasks = scale === 'short' ? '6' : scale === 'long' ? '12–14' : '10'
    return [
      'Структура урока — блоки строго в этом порядке:',
      '1. objectives — 3 цели',
      '2. warmup — 3 вопроса на активацию знаний, без формул, на понимание',
      '3. theory — 3–4 тезиса',
      '4. formulas — все формулы темы с расшифровкой обозначений и единиц',
      '5. example — одна задача, разобранная по шагам',
      `6. tasks — ${tasks} задач по возрастанию сложности, с подсказками к трудным`,
      '7. одно задание на перетаскивание: mysterybox, halves, sorting или matching — что лучше ложится на тему',
      '8. pullout — 4–5 вопросов «почему» по теме, которые ученик вытягивает наугад',
      '9. summary — 3 главные мысли',
      '10. homework — 3 задания',
      '11. answers — ответы ко всем задачам из tasks, с ходом решения',
    ].join('\n')
  }

  const vocab = scale === 'short' ? '5' : scale === 'long' ? '10–12' : '6–8'
  return [
    'Структура урока — блоки строго в этом порядке:',
    '1. objectives — 3 цели',
    '2. warmup — 3 вопроса на английском, чтобы разговорить ученика',
    '3. grammar — правило, таблица форм и типичные ошибки',
    `4. vocabulary — ${vocab} слов с переводом и примером в предложении`,
    '5. halves — сопоставление пар по теме урока (начало и конец фразы, слово и определение)',
    '6. flashlight — 6–8 слов урока, спрятанных в темноте, с заданием в "hunt"',
    '7. gapfill — 4–5 предложений с пропусками плюс 2–3 лишних варианта',
    '8. mysterybox — фраза из 5–7 слов, которую ученик собирает из карточек в коробке',
    '9. pullout — 4–5 вопросов для говорения, которые ученик вытягивает наугад',
    '10. summary — 3 главные мысли',
    '11. homework — 3 задания',
    '12. answers — ключ к halves, gapfill, mysterybox и остальным заданиям',
  ].join('\n')
}

/**
 * Опорный сценарий — приём из школьных онлайн-платформ: у каждого задания
 * есть фраза, которой учитель вводит его вслух. Снимает с репетитора
 * необходимость на ходу придумывать связки между упражнениями.
 */
function teacherScript(request: LessonRequest): string {
  const name = request.student?.trim()
  return [
    'Опорный сценарий для учителя:',
    `— В каждом блоке заполни поле "say": 1–2 живые разговорные фразы, которыми учитель`,
    '  вводит этот блок вслух. Например: «А теперь поможем нашему герою составить текст»,',
    '  «Смотри, что за история тут приключилась». Если задан стиль — фразы в его эстетике.',
    `— Обращайся к ученику на «ты»${name ? ` и по имени (${name})` : ''}.`,
    '— Ученик этих фраз не видит, это подсказка учителю. Не пересказывай в них условие',
    '  задания — только подводку и живость.',
  ].join('\n')
}

